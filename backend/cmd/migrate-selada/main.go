// migrate-selada copies all base tables into an empty PostgreSQL public schema.
// Default execution is read-only. --apply creates the destination if necessary.
package main

import (
	"context"
	"database/sql"
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"

	_ "github.com/go-sql-driver/mysql"
	"github.com/jackc/pgx/v5/pgconn"
	_ "github.com/jackc/pgx/v5/stdlib"
	"go-api/config"
)

type column struct {
	name, kind, full, nullable, extra string
	def                               sql.NullString
}
type index struct {
	name   string
	unique bool
	cols   []string
}
type table struct {
	name    string
	cols    []column
	indexes []index
	count   int64
	next    sql.NullInt64
}
type foreignKey struct {
	table, name, target, update, delete string
	cols, refs                          []string
}

func qi(s string) string      { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
func mi(s string) string      { return "`" + strings.ReplaceAll(s, "`", "``") + "`" }
func literal(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
func pgType(c column) (string, error) {
	switch c.kind {
	case "tinyint":
		return "smallint", nil
	case "smallint":
		if strings.Contains(c.full, "unsigned") {
			return "integer", nil
		}
		return "smallint", nil
	case "mediumint", "int":
		if strings.Contains(c.full, "unsigned") {
			return "bigint", nil
		}
		return "integer", nil
	case "bigint":
		if strings.Contains(c.full, "unsigned") {
			return "numeric(20,0)", nil
		}
		return "bigint", nil
	case "decimal":
		return strings.Split(c.full, " ")[0], nil
	case "float":
		return "real", nil
	case "double":
		return "double precision", nil
	case "varchar", "char":
		return c.full, nil
	case "text", "tinytext", "mediumtext", "longtext":
		return "text", nil
	case "date":
		return "date", nil
	case "datetime", "timestamp":
		return "timestamp without time zone", nil
	}
	return "", fmt.Errorf("unsupported type %s", c.full)
}
func definition(c column) (string, error) {
	typ, err := pgType(c)
	if err != nil {
		return "", err
	}
	out := qi(c.name) + " " + typ
	if strings.Contains(c.extra, "auto_increment") {
		if typ != "smallint" && typ != "integer" && typ != "bigint" {
			return "", fmt.Errorf("unsupported identity type %s", typ)
		}
		return out + " GENERATED BY DEFAULT AS IDENTITY", nil
	}
	if c.extra != "" && c.extra != "DEFAULT_GENERATED" {
		return "", fmt.Errorf("unsupported extra %s", c.extra)
	}
	if c.nullable == "NO" {
		out += " NOT NULL"
	}
	if c.def.Valid {
		if strings.EqualFold(c.def.String, "CURRENT_TIMESTAMP") {
			out += " DEFAULT CURRENT_TIMESTAMP"
		} else {
			out += " DEFAULT " + literal(c.def.String)
		}
	} else if c.nullable == "NO" {
		// The source uses permissive MySQL defaults for omitted fields.
		switch c.kind {
		case "varchar", "char", "text", "tinytext", "mediumtext", "longtext":
			out += " DEFAULT ''"
		case "tinyint", "smallint", "mediumint", "int", "bigint", "decimal", "float", "double":
			out += " DEFAULT 0"
		}
	}
	return out, nil
}
func run(apply bool) error {
	if err := config.LoadEnv(".env"); err != nil {
		return err
	}
	dsn, err := config.SourceMySQLDSN()
	if err != nil {
		return err
	}
	src, err := sql.Open("mysql", dsn)
	if err != nil {
		return err
	}
	defer src.Close()
	ctx := context.Background()
	st, err := src.BeginTx(ctx, &sql.TxOptions{Isolation: sql.LevelRepeatableRead, ReadOnly: true})
	if err != nil {
		return err
	}
	defer st.Rollback()
	var unsupported int
	for _, q := range []string{
		`SELECT COUNT(*) FROM information_schema.tables WHERE table_schema=DATABASE() AND (table_type<>'BASE TABLE' OR engine<>'InnoDB')`,
		`SELECT COUNT(*) FROM information_schema.triggers WHERE trigger_schema=DATABASE()`,
		`SELECT COUNT(*) FROM information_schema.routines WHERE routine_schema=DATABASE()`,
	} {
		if err := st.QueryRow(q).Scan(&unsupported); err != nil {
			return err
		}
		if unsupported > 0 {
			return fmt.Errorf("source has %d unsupported objects; inspect: %s", unsupported, q)
		}
	}
	rows, err := st.Query(`SELECT table_name,auto_increment FROM information_schema.tables WHERE table_schema=DATABASE() AND table_type='BASE TABLE' ORDER BY table_name`)
	if err != nil {
		return err
	}
	var tables []table
	for rows.Next() {
		var t table
		if err := rows.Scan(&t.name, &t.next); err != nil {
			return err
		}
		tables = append(tables, t)
	}
	if err := rows.Err(); err != nil {
		return err
	}
	rows.Close()
	for i := range tables {
		t := &tables[i]
		rows, err = st.Query(`SELECT column_name,data_type,column_type,is_nullable,column_default,extra FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name=? ORDER BY ordinal_position`, t.name)
		if err != nil {
			return err
		}
		for rows.Next() {
			var c column
			if err := rows.Scan(&c.name, &c.kind, &c.full, &c.nullable, &c.def, &c.extra); err != nil {
				return err
			}
			if _, err := definition(c); err != nil {
				return fmt.Errorf("%s.%s: %w", t.name, c.name, err)
			}
			t.cols = append(t.cols, c)
		}
		if err := rows.Err(); err != nil {
			return err
		}
		rows.Close()
		rows, err = st.Query(`SELECT index_name,non_unique,column_name,sub_part,index_type FROM information_schema.statistics WHERE table_schema=DATABASE() AND table_name=? ORDER BY index_name,seq_in_index`, t.name)
		if err != nil {
			return err
		}
		for rows.Next() {
			var name, cn, it string
			var nu int
			var part sql.NullInt64
			if err := rows.Scan(&name, &nu, &cn, &part, &it); err != nil {
				return err
			}
			if part.Valid || it != "BTREE" {
				return fmt.Errorf("unsupported index %s.%s", t.name, name)
			}
			if len(t.indexes) == 0 || t.indexes[len(t.indexes)-1].name != name {
				t.indexes = append(t.indexes, index{name: name, unique: nu == 0})
			}
			ix := &t.indexes[len(t.indexes)-1]
			ix.cols = append(ix.cols, qi(cn))
		}
		if err := rows.Err(); err != nil {
			return err
		}
		rows.Close()
		if err := st.QueryRow("SELECT COUNT(*) FROM " + mi(t.name)).Scan(&t.count); err != nil {
			return err
		}
		fmt.Printf("%-25s %d rows\n", t.name, t.count)
		for _, c := range t.cols {
			if c.kind == "date" || c.kind == "datetime" || c.kind == "timestamp" {
				var n int64
				if err := st.QueryRow("SELECT COUNT(*) FROM " + mi(t.name) + " WHERE CAST(" + mi(c.name) + " AS CHAR) LIKE '0000-%'").Scan(&n); err != nil {
					return err
				}
				if n > 0 {
					return fmt.Errorf("%s.%s: %d zero dates require an explicit conversion policy", t.name, c.name, n)
				}
			}
		}
	}
	var fks []foreignKey
	rows, err = st.Query(`SELECT k.table_name,k.constraint_name,k.column_name,k.referenced_table_name,k.referenced_column_name,r.update_rule,r.delete_rule FROM information_schema.key_column_usage k JOIN information_schema.referential_constraints r ON r.constraint_schema=k.constraint_schema AND r.table_name=k.table_name AND r.constraint_name=k.constraint_name WHERE k.constraint_schema=DATABASE() AND k.referenced_table_name IS NOT NULL ORDER BY k.table_name,k.constraint_name,k.ordinal_position`)
	if err != nil {
		return err
	}
	for rows.Next() {
		var f foreignKey
		var cn, rn string
		if err = rows.Scan(&f.table, &f.name, &cn, &f.target, &rn, &f.update, &f.delete); err != nil {
			return err
		}
		if len(fks) == 0 || fks[len(fks)-1].table != f.table || fks[len(fks)-1].name != f.name {
			fks = append(fks, f)
		}
		last := &fks[len(fks)-1]
		last.cols = append(last.cols, qi(cn))
		last.refs = append(last.refs, qi(rn))
	}
	if err = rows.Err(); err != nil {
		return err
	}
	rows.Close()
	dsn, err = config.PostgresDSN("DB_PG2", "")
	if err != nil {
		return err
	}
	dst, err := sql.Open("pgx", dsn)
	if err != nil {
		return err
	}
	defer dst.Close()
	if err = dst.Ping(); err != nil {
		var pe *pgconn.PgError
		if !errors.As(err, &pe) || pe.Code != "3D000" {
			return err
		}
		if !apply {
			fmt.Println("Destination database does not exist; --apply will create it.")
			return nil
		}
		adminDSN, e := config.PostgresDSN("DB_PG2", "postgres")
		if e != nil {
			return e
		}
		admin, e := sql.Open("pgx", adminDSN)
		if e != nil {
			return e
		}
		defer admin.Close()
		if _, e = admin.Exec("CREATE DATABASE " + qi(os.Getenv("DB_PG2_NAME"))); e != nil {
			return e
		}
	}
	dt, err := dst.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer dt.Rollback()
	var existing int
	if err = dt.QueryRow(`SELECT COUNT(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','S','f')`).Scan(&existing); err != nil {
		return err
	}
	if existing != 0 {
		return fmt.Errorf("destination public schema is not empty; refusing to overwrite existing objects")
	}
	if !apply {
		fmt.Println("Preflight OK. Run with --apply to copy all tables.")
		return nil
	}
	if _, err = dt.Exec(`SET LOCAL standard_conforming_strings = on`); err != nil {
		return err
	}
	var total int64
	for _, t := range tables {
		var defs, names, sourceNames, params []string
		for i, c := range t.cols {
			d, _ := definition(c)
			defs = append(defs, d)
			names = append(names, qi(c.name))
			sourceNames = append(sourceNames, mi(c.name))
			params = append(params, fmt.Sprintf("$%d", i+1))
		}
		for _, ix := range t.indexes {
			if ix.name == "PRIMARY" {
				defs = append(defs, "PRIMARY KEY ("+strings.Join(ix.cols, ",")+")")
			}
		}
		if _, err = dt.Exec("CREATE TABLE public." + qi(t.name) + " (" + strings.Join(defs, ",") + ")"); err != nil {
			return err
		}
		insert := "INSERT INTO public." + qi(t.name) + " (" + strings.Join(names, ",") + ") VALUES "
		var batch []any
		var groups []string
		flush := func() error {
			if len(groups) == 0 {
				return nil
			}
			_, e := dt.Exec(insert+strings.Join(groups, ","), batch...)
			batch = nil
			groups = nil
			return e
		}
		rows, err = st.Query("SELECT " + strings.Join(sourceNames, ",") + " FROM " + mi(t.name))
		if err != nil {
			return err
		}
		var copied int64
		for rows.Next() {
			vals := make([]any, len(t.cols))
			ptrs := make([]any, len(vals))
			for i := range vals {
				ptrs[i] = &vals[i]
			}
			if err = rows.Scan(ptrs...); err != nil {
				return err
			}
			for i, v := range vals {
				if b, ok := v.([]byte); ok {
					vals[i] = string(b)
				}
				if s, ok := vals[i].(string); ok && (t.cols[i].kind == "date" || t.cols[i].kind == "datetime" || t.cols[i].kind == "timestamp") && strings.HasPrefix(s, "0000-") {
					return fmt.Errorf("%s.%s contains zero dates; migration rolled back, source unchanged", t.name, t.cols[i].name)
				}
			}
			marks := make([]string, len(vals))
			for i := range vals {
				marks[i] = fmt.Sprintf("$%d", len(batch)+i+1)
			}
			groups = append(groups, "("+strings.Join(marks, ",")+")")
			batch = append(batch, vals...)
			if len(groups) == 250 {
				if err = flush(); err != nil {
					return fmt.Errorf("copy %s: %w", t.name, err)
				}
			}
			copied++
		}
		if err = rows.Err(); err != nil {
			return err
		}
		rows.Close()
		if err = flush(); err != nil {
			return fmt.Errorf("copy %s: %w", t.name, err)
		}
		var count int64
		if err = dt.QueryRow("SELECT COUNT(*) FROM public." + qi(t.name)).Scan(&count); err != nil {
			return err
		}
		if copied != t.count || count != t.count {
			return fmt.Errorf("row count mismatch for %s", t.name)
		}
		for _, ix := range t.indexes {
			if ix.name == "PRIMARY" {
				continue
			}
			unique := ""
			if ix.unique {
				unique = "UNIQUE "
			}
			if _, err = dt.Exec("CREATE " + unique + "INDEX " + qi(t.name+"_"+ix.name) + " ON public." + qi(t.name) + " (" + strings.Join(ix.cols, ",") + ")"); err != nil {
				return err
			}
		}
		for _, c := range t.cols {
			if strings.Contains(c.extra, "auto_increment") {
				next := int64(1)
				if t.next.Valid {
					next = t.next.Int64
				}
				q := "SELECT setval(pg_get_serial_sequence($1,$2), GREATEST(COALESCE(MAX(" + qi(c.name) + "),0)+1,$3),false) FROM public." + qi(t.name)
				if _, err = dt.Exec(q, "public."+qi(t.name), c.name, next); err != nil {
					return err
				}
			}
		}
		total += copied
		fmt.Printf("Verified %-25s %d rows\n", t.name, copied)
	}
	for _, f := range fks {
		q := "ALTER TABLE public." + qi(f.table) + " ADD CONSTRAINT " + qi(f.name) + " FOREIGN KEY (" + strings.Join(f.cols, ",") + ") REFERENCES public." + qi(f.target) + " (" + strings.Join(f.refs, ",") + ") ON UPDATE " + f.update + " ON DELETE " + f.delete
		if _, err = dt.Exec(q); err != nil {
			return err
		}
	}
	if err = dt.Commit(); err != nil {
		return err
	}
	fmt.Printf("Migration committed: %d tables, %d rows. MySQL source unchanged.\n", len(tables), total)
	return nil
}
func main() {
	apply := flag.Bool("apply", false, "create destination and copy data")
	flag.Parse()
	if err := run(*apply); err != nil {
		log.Fatal(err)
	}
}
